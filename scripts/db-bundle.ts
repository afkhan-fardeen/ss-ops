/**
 * Concatenates every migration into supabase/setup.sql — one file you can paste into the Supabase SQL editor
 * to build the whole schema on a brand-new project (alternative to `npm run db:push`).
 * Usage: npm run db:bundle
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const parts = files.map((f) => `-- ============================================================\n-- ${f}\n-- ============================================================\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
const header = `-- Seissense Ops — full database setup (generated by \`npm run db:bundle\`; do not edit by hand).\n-- Safe to re-run: every migration is idempotent.\n-- ${files.length} migrations, ${new Date().toISOString()}\n\n`;
writeFileSync(join(process.cwd(), "supabase", "setup.sql"), header + parts.join("\n"));
console.log(`Wrote supabase/setup.sql from ${files.length} migrations.`);
